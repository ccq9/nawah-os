#!/usr/bin/env python3
"""tools/text_vectors.py — the guest's sample of the text tests (WP-35, TST-M5-TEXT-GUEST):
writes user/apps/textprobe/src/vectors.rs with expected values from independent sources —

  BIDI    every 911th line of BidiCharacterTest-17.0.0 with at most 24 code points (the
          Unicode conformance data: paragraph level, levels, visual order)
  SHAPE   Arabic words with the glyph ids HarfBuzz (hb-shape) gives on the shipped font
  RASTER  glyph bitmaps' hashes from the host build of nawah-text (host and guest agree)

Usage: text_vectors.py [--check]   (needs hb-shape and the host examples, built by
tests/test_text.py or `cargo build --release -p nawah-text --examples`)."""
import lzma, pathlib, subprocess, sys, tempfile, os

ROOT = pathlib.Path(__file__).resolve().parent.parent
UCD = ROOT / "user" / "libnawah-text" / "ucd"
FONTS = ROOT / "platform" / "assets" / "fonts"
OUT = ROOT / "user" / "apps" / "textprobe" / "src" / "vectors.rs"
TEXTDUMP = ROOT / "target" / "x86_64-unknown-linux-gnu" / "release" / "examples" / "textdump"

WORDS = ["السلام", "عليكم", "مرحبا", "بالعالم", "لا", "الله", "مستشفى", "يكتبون", "مسؤول", "لأن", "إلى", "آمن",
         "فلاح", "مصطفى", "موسيقى", "شيء", "ماء", "ه", "اه", "نواة", "نظام", "تشغيل", "حاسوب", "شاشة", "لوحة",
         "مفاتيح", "فأرة", "نافذة", "قفل", "دخول", "كلمة", "مرور", "ضغط", "ظل", "غيث", "ثلج", "خوخ", "ذرة", "زيت",
         "صقر"]
RASTER = [("latin", "a", 16), ("latin", "g", 24), ("latin", "@", 32), ("latin", "8", 12),
          ("arabic", "ش", 16), ("arabic", "ع", 24), ("arabic", "ك", 32), ("arabic", "ه", 12)]


def bidi_vectors():
    lines = lzma.decompress((UCD / "BidiCharacterTest.txt.xz").read_bytes()).decode("utf-8").splitlines()
    data = [l for l in lines if l and not l.startswith("#")]
    out = []
    for i, l in enumerate(data):
        if i % 911:
            continue
        f = l.split(";")
        cps = [int(x, 16) for x in f[0].split()]
        if len(cps) > 24:
            continue
        levels = [255 if t == "x" else int(t) for t in f[3].split()]
        order = [int(t) for t in f[4].split()]
        out.append((cps, int(f[1]), int(f[2]), levels, order))
    return out


def shape_vectors():
    with tempfile.NamedTemporaryFile("w", delete=False, encoding="utf-8") as t:
        t.write("\n".join(WORDS) + "\n")
        name = t.name
    try:
        r = subprocess.run(["hb-shape", "--font-file", str(FONTS / "NotoSansArabic-Regular.ttf"), "--direction=rtl",
                            "--script=arab", "--language=ar", "--no-glyph-names", "--no-positions", "--no-clusters",
                            "--text-file", name], capture_output=True, text=True, check=True)
    finally:
        os.unlink(name)
    gids = [list(reversed([int(g) for g in x.strip().strip("[]").split("|")])) for x in r.stdout.splitlines()]
    return [([ord(c) for c in w], g) for w, g in zip(WORDS, gids)]


def raster_vectors():
    from fontTools.ttLib import TTFont
    fonts = {"latin": TTFont(str(FONTS / "NotoSans-Regular.ttf")), "arabic": TTFont(str(FONTS / "NotoSansArabic-Regular.ttf"))}
    cmds, rows = [], []
    for name, ch, px in RASTER:
        f = fonts[name]
        gid = f.getGlyphID(f.getBestCmap()[ord(ch)])
        cmds.append(f"hash {name} {gid} {px}")
        rows.append((0 if name == "latin" else 1, gid, px))
    r = subprocess.run([str(TEXTDUMP), str(FONTS / "NotoSans-Regular.ttf"), str(FONTS / "NotoSansArabic-Regular.ttf")],
                       input="\n".join(cmds) + "\n", capture_output=True, text=True, check=True)
    return [(f, g, p, int(h, 16)) for (f, g, p), h in zip(rows, r.stdout.split())]


def arr(xs, fmt="{}"):
    return "&[" + ", ".join(fmt.format(x) for x in xs) + "]"


def render():
    b, s, r = bidi_vectors(), shape_vectors(), raster_vectors()
    o = ["//! Generated by tools/text_vectors.py — do not edit. Expected values: BidiCharacterTest-17.0.0",
         "//! (Unicode, Inc.; Unicode License v3), HarfBuzz hb-shape on NotoSansArabic-Regular.ttf, and",
         "//! the host build of nawah-text for the bitmap hashes.", "",
         "pub struct BidiVector {", "    pub text: &'static [u32],", "    pub base: u8,", "    pub para: u8,",
         "    pub levels: &'static [u8],", "    pub order: &'static [u16],", "}", "",
         "pub struct ShapeVector {", "    pub text: &'static [u32],", "    pub glyphs: &'static [u16],", "}", "",
         "pub struct RasterVector {", "    pub font: u8,", "    pub gid: u16,", "    pub px: u32,", "    pub hash: u64,", "}", "",
         f"pub static BIDI: [BidiVector; {len(b)}] = ["]
    for cps, base, para, levels, order in b:
        o.append(f"    BidiVector {{ text: {arr(cps, '0x{:X}')}, base: {base}, para: {para}, levels: {arr(levels)}, order: {arr(order)} }},")
    o += ["];", "", f"pub static SHAPE: [ShapeVector; {len(s)}] = ["]
    for cps, g in s:
        o.append(f"    ShapeVector {{ text: {arr(cps, '0x{:X}')}, glyphs: {arr(g)} }},")
    o += ["];", "", f"pub static RASTER: [RasterVector; {len(r)}] = ["]
    for f, g, p, h in r:
        o.append(f"    RasterVector {{ font: {f}, gid: {g}, px: {p}, hash: 0x{h:016x} }},")
    o += ["];", ""]
    return "\n".join(o)


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("vectors.rs is current" if ok else "vectors.rs is stale: run tools/text_vectors.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
