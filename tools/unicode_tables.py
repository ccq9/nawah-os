#!/usr/bin/env python3
"""tools/unicode_tables.py — generates user/libnawah-text/src/tables.rs from the Unicode
Character Database files kept under user/libnawah-text/ucd/ (WP-35, ADR-0019 §6):

  DerivedBidiClass.txt   → BIDI: (first code point, class) ranges; a code point's class is the
                           entry of the last range starting at or below it (the file's
                           @missing defaults seed the table, so unassigned code points in the
                           right-to-left blocks are R/AL as UAX #9 says)
  DerivedJoiningType.txt → JOINING: (first, last, type) for the Arabic-script joining types
                           (R, L, D, C, T); everything else is U
  BidiBrackets.txt       → BRACKETS: (code point, pair, is_open) for rule N0

Run it after replacing the UCD files; the test TST-M5-BIDI-TABLES checks the output is
current. Usage: unicode_tables.py [--check]
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UCD = ROOT / "user" / "libnawah-text" / "ucd"
OUT = ROOT / "user" / "libnawah-text" / "src" / "tables.rs"

CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
LONG = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Number": "EN",
        "European_Separator": "ES", "European_Terminator": "ET", "Arabic_Number": "AN",
        "Common_Separator": "CS", "Nonspacing_Mark": "NSM", "Boundary_Neutral": "BN",
        "Paragraph_Separator": "B", "Segment_Separator": "S", "White_Space": "WS",
        "Other_Neutral": "ON", "Left_To_Right_Embedding": "LRE", "Left_To_Right_Override": "LRO",
        "Right_To_Left_Embedding": "RLE", "Right_To_Left_Override": "RLO", "Pop_Directional_Format": "PDF",
        "Left_To_Right_Isolate": "LRI", "Right_To_Left_Isolate": "RLI", "First_Strong_Isolate": "FSI",
        "Pop_Directional_Isolate": "PDI"}
JOIN = {"R": 1, "L": 2, "D": 3, "C": 4, "T": 5}


def ranges_of(path, value_map):
    """(first, last, value) from a UCD property file; @missing lines first (defaults)."""
    missing, entries = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+);\s*([A-Za-z_]+)", line)
        if m:
            missing.append((int(m.group(1), 16), int(m.group(2), 16), value_map(m.group(3))))
            continue
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, value = [x.strip() for x in line.split(";")[:2]]
        first, last = (cps.split("..") + [None])[:2]
        first = int(first, 16)
        last = int(last, 16) if last else first
        entries.append((first, last, value_map(value)))
    return missing, entries


def bidi_table():
    missing, entries = ranges_of(UCD / "DerivedBidiClass.txt", lambda v: LONG.get(v, v))
    table = {}
    for first, last, cls in missing:  # later defaults override earlier (the file lists the
        for cp in range(first, last + 1):  # broad 0000..10FFFF L first)
            table[cp] = cls
    for first, last, cls in entries:
        for cp in range(first, last + 1):
            table[cp] = cls
    runs, cur = [], None
    for cp in range(0x110000):
        cls = table[cp]
        if cls != cur:
            runs.append((cp, cls))
            cur = cls
    return runs


def joining_table():
    _, entries = ranges_of(UCD / "DerivedJoiningType.txt", lambda v: v)
    rows = sorted((f, l, JOIN[t]) for f, l, t in entries if t in JOIN)
    merged = []
    for f, l, t in rows:
        if merged and merged[-1][2] == t and merged[-1][1] + 1 == f:
            merged[-1] = (merged[-1][0], l, t)
        else:
            merged.append((f, l, t))
    return merged


def bracket_table():
    rows = []
    for line in (UCD / "BidiBrackets.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        cp, pair, kind = [x.strip() for x in line.split(";")]
        rows.append((int(cp, 16), int(pair, 16), kind == "o"))
    return sorted(rows)


def versions():
    v = {}
    for name in ("DerivedBidiClass", "DerivedJoiningType", "BidiBrackets"):
        head = (UCD / f"{name}.txt").read_text(encoding="utf-8").splitlines()[0]
        v[name] = head.lstrip("# ").strip()
    return v


def render():
    bidi, join, br = bidi_table(), joining_table(), bracket_table()
    v = versions()
    out = ["//! Generated by tools/unicode_tables.py from the Unicode Character Database files under",
           "//! user/libnawah-text/ucd/ — do not edit:",
           *(f"//!   {k}: {val}" for k, val in v.items()),
           "//! © Unicode, Inc.; data files under the Unicode License v3 (https://www.unicode.org/license.txt).",
           "", "#![allow(clippy::unreadable_literal)]", "",
           "/// Bidi classes in the order UAX #9 names them (`BIDI` stores the index).",
           "pub const CLASS_NAMES: [&str; %d] = [%s];" % (len(CLASSES), ", ".join('"%s"' % c for c in CLASSES)),
           "", "/// (first code point, class index): the class of a code point is that of the last entry",
           "/// whose first code point is <= it (binary search).",
           "pub static BIDI: [(u32, u8); %d] = [" % len(bidi)]
    out += ["    (0x%X, %d)," % (cp, CLASSES.index(cls)) for cp, cls in bidi]
    out += ["];", "", "/// Arabic-script joining types: (first, last, type) with 1 = R, 2 = L, 3 = D, 4 = C, 5 = T;",
            "/// code points outside every range are U (non-joining).",
            "pub static JOINING: [(u32, u32, u8); %d] = [" % len(join)]
    out += ["    (0x%X, 0x%X, %d)," % r for r in join]
    out += ["];", "", "/// Bracket pairs for rule N0: (code point, its pair, is an opening bracket).",
            "pub static BRACKETS: [(u32, u32, bool); %d] = [" % len(br)]
    out += ["    (0x%X, 0x%X, %s)," % (a, b, "true" if o else "false") for a, b, o in br]
    out += ["];", ""]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
            print("tables.rs is current"); return 0
        print("tables.rs is stale: run tools/unicode_tables.py"); return 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
